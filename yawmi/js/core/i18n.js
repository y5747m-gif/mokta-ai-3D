let current = 'ar';

export function getLang() { return current; }

export function setLang(lang) {
  current = lang === 'en' ? 'en' : 'ar';
  return current;
}

/** ترجمة بالمفتاح مع ارتداد للعربية */
export function t(key) {
  const dict = current === 'en' ? EN : AR;
  return dict[key] ?? AR[key] ?? EN[key] ?? key;
}

/** اختيار سريع بين نصين حسب اللغة الحالية */
export function L(ar, en) {
  return current === 'en' ? en : ar;
}

export function isRTL() { return current !== 'en'; }
